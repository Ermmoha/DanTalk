$wNs = 'http://schemas.openxmlformats.org/wordprocessingml/2006/main'
$xmlNs = 'http://www.w3.org/XML/1998/namespace'

function Read-EntryText {
    param(
        [System.IO.Compression.ZipArchive]$Zip,
        [string]$Name
    )
    $entry = $Zip.GetEntry($Name)
    if ($null -eq $entry) { return $null }
    $stream = $entry.Open()
    try {
        $reader = [System.IO.StreamReader]::new($stream, [System.Text.Encoding]::UTF8)
        try { return $reader.ReadToEnd() } finally { $reader.Dispose() }
    } finally {
        $stream.Dispose()
    }
}

function Save-EntryText {
    param(
        [System.IO.Compression.ZipArchive]$Zip,
        [string]$Name,
        [string]$Text
    )
    $old = $Zip.GetEntry($Name)
    if ($null -ne $old) { $old.Delete() }
    $entry = $Zip.CreateEntry($Name, [System.IO.Compression.CompressionLevel]::Optimal)
    $stream = $entry.Open()
    try {
        $bytes = [System.Text.UTF8Encoding]::new($false).GetBytes($Text)
        $stream.Write($bytes, 0, $bytes.Length)
    } finally {
        $stream.Dispose()
    }
}

function New-WordNamespaceManager {
    param([xml]$Xml)
    $ns = [System.Xml.XmlNamespaceManager]::new($Xml.NameTable)
    $ns.AddNamespace('w', $wNs)
    return ,$ns
}

function Set-ParagraphText {
    param(
        [xml]$Xml,
        [System.Xml.XmlNamespaceManager]$Ns,
        [int]$Index,
        [string]$Text
    )

    $paras = $Xml.SelectNodes('//w:p', $Ns)
    if ($Index -lt 0 -or $Index -ge $paras.Count) { return }

    $p = $paras[$Index]
    $texts = $p.SelectNodes('.//w:t', $Ns)

    if ($texts.Count -eq 0) {
        if ([string]::IsNullOrEmpty($Text)) { return }
        $r = $Xml.CreateElement('w', 'r', $wNs)
        $t = $Xml.CreateElement('w', 't', $wNs)
        $space = $Xml.CreateAttribute('xml', 'space', $xmlNs)
        $space.Value = 'preserve'
        [void]$t.Attributes.Append($space)
        $t.InnerText = $Text
        [void]$r.AppendChild($t)
        [void]$p.AppendChild($r)
        return
    }

    $texts[0].InnerText = $Text
    for ($i = 1; $i -lt $texts.Count; $i++) {
        $texts[$i].InnerText = ''
    }
}

function Replace-TextNodes {
    param(
        [System.Xml.XmlNode]$Node,
        [hashtable]$Replacements
    )

    if ($Node.NodeType -eq [System.Xml.XmlNodeType]::Text) {
        $value = $Node.Value
        foreach ($key in $Replacements.Keys) {
            $value = $value.Replace($key, $Replacements[$key])
        }
        $Node.Value = $value
        return
    }

    foreach ($child in @($Node.ChildNodes)) {
        Replace-TextNodes -Node $child -Replacements $Replacements
    }
}

function Save-XmlToEntry {
    param(
        [System.IO.Compression.ZipArchive]$Zip,
        [string]$Name,
        [xml]$Xml
    )
    $settings = [System.Xml.XmlWriterSettings]::new()
    $settings.Encoding = [System.Text.UTF8Encoding]::new($false)
    $settings.Indent = $false
    $settings.OmitXmlDeclaration = $false
    $old = $Zip.GetEntry($Name)
    if ($null -ne $old) { $old.Delete() }
    $entry = $Zip.CreateEntry($Name, [System.IO.Compression.CompressionLevel]::Optimal)
    $stream = $entry.Open()
    $writer = [System.Xml.XmlWriter]::Create($stream, $settings)
    try { $Xml.Save($writer) } finally { $writer.Dispose(); $stream.Dispose() }
}

function Draw-WrappedText {
    param(
        [System.Drawing.Graphics]$Graphics,
        [string]$Text,
        [System.Drawing.Font]$Font,
        [System.Drawing.Brush]$Brush,
        [float]$X,
        [float]$Y,
        [float]$Width,
        [float]$LineHeight
    )

    $words = $Text -split '\s+'
    $line = ''
    foreach ($word in $words) {
        if ([string]::IsNullOrWhiteSpace($word)) { continue }
        $candidate = if ($line.Length -eq 0) { $word } else { "$line $word" }
        if ($Graphics.MeasureString($candidate, $Font).Width -gt $Width -and $line.Length -gt 0) {
            $Graphics.DrawString($line, $Font, $Brush, $X, $Y)
            $Y += $LineHeight
            $line = $word
        } else {
            $line = $candidate
        }
    }
    if ($line.Length -gt 0) {
        $Graphics.DrawString($line, $Font, $Brush, $X, $Y)
        $Y += $LineHeight
    }
    return $Y
}

function Draw-Box {
    param(
        [System.Drawing.Graphics]$Graphics,
        [float]$X,
        [float]$Y,
        [float]$W,
        [float]$H,
        [string]$Text,
        [System.Drawing.Font]$Font,
        [System.Drawing.Brush]$TextBrush,
        [System.Drawing.Brush]$FillBrush,
        [System.Drawing.Pen]$Pen
    )
    $Graphics.FillRectangle($FillBrush, $X, $Y, $W, $H)
    $Graphics.DrawRectangle($Pen, $X, $Y, $W, $H)
    [void](Draw-WrappedText -Graphics $Graphics -Text $Text -Font $Font -Brush $TextBrush -X ($X + 14) -Y ($Y + 14) -Width ($W - 28) -LineHeight ($Font.Size + 8))
}

function New-ImageBytes {
    param(
        [int]$Width,
        [int]$Height,
        [hashtable]$Spec
    )

    if ($Width -lt 400) { $Width = 900 }
    if ($Height -lt 300) { $Height = 620 }

    $bmp = [System.Drawing.Bitmap]::new($Width, $Height)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.SmoothingMode = [System.Drawing.Drawing2D.SmoothingMode]::AntiAlias
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::ClearTypeGridFit

    $white = [System.Drawing.SolidBrush]::new([System.Drawing.Color]::White)
    $light = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#F5F8FA'))
    $accent = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#00BFFF'))
    $accentAlt = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#0394C5'))
    $dark = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#151515'))
    $muted = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#5A5A5A'))
    $red = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#FF5454'))
    $linePen = [System.Drawing.Pen]::new([System.Drawing.ColorTranslator]::FromHtml('#0394C5'), 3)
    $softPen = [System.Drawing.Pen]::new([System.Drawing.ColorTranslator]::FromHtml('#C8DDE8'), 2)
    $titleFont = [System.Drawing.Font]::new('Arial', [Math]::Max(18, [int]($Width / 38)), [System.Drawing.FontStyle]::Bold)
    $subtitleFont = [System.Drawing.Font]::new('Arial', [Math]::Max(11, [int]($Width / 75)), [System.Drawing.FontStyle]::Regular)
    $boxFont = [System.Drawing.Font]::new('Arial', [Math]::Max(12, [int]($Width / 68)), [System.Drawing.FontStyle]::Regular)
    $smallFont = [System.Drawing.Font]::new('Arial', [Math]::Max(10, [int]($Width / 90)), [System.Drawing.FontStyle]::Regular)

    try {
        $g.FillRectangle($white, 0, 0, $Width, $Height)
        $g.FillRectangle($light, 0, 0, $Width, $Height)
        $g.FillRectangle($accent, 0, 0, $Width, [Math]::Max(58, [int]($Height * 0.11)))
        $g.DrawString($Spec.Title, $titleFont, [System.Drawing.Brushes]::White, 28, 18)

        $mode = $Spec.Mode
        $lines = @($Spec.Lines)
        if ($mode -eq 'phone') {
            $phoneW = [Math]::Min([int]($Width * 0.44), 390)
            $phoneH = [Math]::Min([int]($Height * 0.78), 720)
            $x = [int](($Width - $phoneW) / 2)
            $y = [int]($Height * 0.16)
            $g.FillRectangle($dark, $x, $y, $phoneW, $phoneH)
            $g.FillRectangle($white, $x + 12, $y + 12, $phoneW - 24, $phoneH - 24)
            $g.FillRectangle($accentAlt, $x + 12, $y + 12, $phoneW - 24, 58)
            $g.DrawString('DanTalk', $subtitleFont, [System.Drawing.Brushes]::White, $x + 28, $y + 31)
            $cy = $y + 92
            foreach ($line in $lines) {
                $g.FillRectangle([System.Drawing.Brushes]::WhiteSmoke, $x + 32, $cy, $phoneW - 64, 54)
                $g.DrawRectangle($softPen, $x + 32, $cy, $phoneW - 64, 54)
                $g.DrawString($line, $smallFont, $dark, $x + 46, $cy + 16)
                $cy += 68
                if ($cy -gt ($y + $phoneH - 88)) { break }
            }
            $g.FillRectangle($accent, $x + 45, $y + $phoneH - 76, $phoneW - 90, 42)
            $g.DrawString($Spec.Footer, $smallFont, [System.Drawing.Brushes]::White, $x + 62, $y + $phoneH - 64)
        } elseif ($mode -eq 'palette') {
            $colors = @(
                @('#00BFFF', 'MainColor'),
                @('#0394C5', 'AltMainColor'),
                @('#F5F5F5', 'Light background'),
                @('#151515', 'Dark surface'),
                @('#5A5A5A', 'Hint text'),
                @('#FF5454', 'Danger')
            )
            $startX = 65
            $startY = [int]($Height * 0.24)
            $sw = [int](($Width - 160) / 3)
            $sh = [int](($Height - $startY - 80) / 2)
            for ($i = 0; $i -lt $colors.Count; $i++) {
                $cx = $startX + ($i % 3) * ($sw + 15)
                $cy = $startY + [int]($i / 3) * ($sh + 18)
                $brush = [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml($colors[$i][0]))
                $g.FillRectangle($brush, $cx, $cy, $sw, $sh)
                $g.DrawRectangle($linePen, $cx, $cy, $sw, $sh)
                $g.DrawString($colors[$i][1], $boxFont, $dark, $cx + 16, $cy + $sh - 48)
                $g.DrawString($colors[$i][0], $smallFont, $muted, $cx + 16, $cy + $sh - 24)
                $brush.Dispose()
            }
        } elseif ($mode -eq 'chart') {
            $left = 80
            $top = [int]($Height * 0.23)
            $right = $Width - 70
            $bottom = $Height - 80
            $g.DrawLine($linePen, $left, $bottom, $right, $bottom)
            $g.DrawLine($linePen, $left, $top, $left, $bottom)
            for ($i = 0; $i -lt 6; $i++) {
                $yy = $top + ($bottom - $top) * $i / 5
                $g.DrawLine($softPen, $left, $yy, $right, $yy)
            }
            $points = New-Object 'System.Collections.Generic.List[System.Drawing.PointF]'
            for ($i = 0; $i -lt 18; $i++) {
                $px = $left + ($right - $left) * $i / 17
                $value = 0.42 + 0.18 * [Math]::Sin($i * 0.9)
                if ($Spec.Title -match 'памяти') { $value = 0.58 + 0.13 * [Math]::Sin($i * 0.7) }
                if ($Spec.Title -match 'интерфейса') { $value = 0.25 + 0.2 * [Math]::Abs([Math]::Sin($i * 1.2)) }
                $py = $bottom - ($bottom - $top) * $value
                $points.Add([System.Drawing.PointF]::new($px, $py))
            }
            $g.DrawLines([System.Drawing.Pen]::new([System.Drawing.ColorTranslator]::FromHtml('#00BFFF'), 5), $points.ToArray())
            [void](Draw-WrappedText -Graphics $g -Text ($lines -join ' ') -Font $boxFont -Brush $dark -X 90 -Y ($Height - 58) -Width ($Width - 180) -LineHeight ($boxFont.Size + 6))
        } else {
            $cols = if ($lines.Count -le 4) { 2 } else { 3 }
            $rows = [Math]::Ceiling($lines.Count / $cols)
            $margin = 55
            $top = [int]($Height * 0.22)
            $boxW = [int](($Width - 2 * $margin - ($cols - 1) * 25) / $cols)
            $boxH = [int](($Height - $top - 70 - ($rows - 1) * 22) / [Math]::Max(1, $rows))
            for ($i = 0; $i -lt $lines.Count; $i++) {
                $cx = $margin + ($i % $cols) * ($boxW + 25)
                $cy = $top + [int]($i / $cols) * ($boxH + 22)
                $fill = if ($i % 5 -eq 0) { [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#E8F8FF')) } else { [System.Drawing.SolidBrush]::new([System.Drawing.ColorTranslator]::FromHtml('#FFFFFF')) }
                Draw-Box -Graphics $g -X $cx -Y $cy -W $boxW -H $boxH -Text $lines[$i] -Font $boxFont -TextBrush $dark -FillBrush $fill -Pen $linePen
                $fill.Dispose()
            }
            if ($Spec.Footer) {
                [void](Draw-WrappedText -Graphics $g -Text $Spec.Footer -Font $subtitleFont -Brush $muted -X 58 -Y ($Height - 48) -Width ($Width - 116) -LineHeight ($subtitleFont.Size + 6))
            }
        }

        $ms = [System.IO.MemoryStream]::new()
        try {
            $bmp.Save($ms, [System.Drawing.Imaging.ImageFormat]::Png)
            return $ms.ToArray()
        } finally {
            $ms.Dispose()
        }
    } finally {
        $g.Dispose()
        $bmp.Dispose()
        $white.Dispose()
        $light.Dispose()
        $accent.Dispose()
        $accentAlt.Dispose()
        $dark.Dispose()
        $muted.Dispose()
        $red.Dispose()
        $linePen.Dispose()
        $softPen.Dispose()
        $titleFont.Dispose()
        $subtitleFont.Dispose()
        $boxFont.Dispose()
        $smallFont.Dispose()
    }
}

