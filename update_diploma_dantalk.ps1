function Update-WordPart {
    param(
        [System.IO.Compression.ZipArchive]$Zip,
        [string]$Name,
        [bool]$ApplyParagraphMap
    )

    $text = Read-EntryText -Zip $Zip -Name $Name
    if ($null -eq $text) { return }
    [xml]$xml = $text
    Replace-TextNodes -Node $xml -Replacements $globalReplacements

    if ($ApplyParagraphMap) {
        $ns = New-WordNamespaceManager -Xml $xml
        $paras = $xml.SelectNodes('//w:p', $ns)
        for ($i = 112; $i -le 777 -and $i -lt $paras.Count; $i++) {
            $oldText = ($paras[$i].SelectNodes('.//w:t', $ns) | ForEach-Object { $_.InnerText }) -join ''
            if ($oldText.Trim().Length -gt 0 -and -not $map.ContainsKey($i)) {
                Set-ParagraphText -Xml $xml -Ns $ns -Index $i -Text ''
            }
        }
        foreach ($idx in ($map.Keys | Sort-Object)) {
            Set-ParagraphText -Xml $xml -Ns $ns -Index ([int]$idx) -Text $map[$idx]
        }
    }

    Save-XmlToEntry -Zip $Zip -Name $Name -Xml $xml
}

function Clean-RawXmlEntries {
    param([System.IO.Compression.ZipArchive]$Zip)

    foreach ($entry in @($Zip.Entries | Where-Object { $_.FullName -match '\.xml$' })) {
        $text = Read-EntryText -Zip $Zip -Name $entry.FullName
        if ($null -eq $text) { continue }
        foreach ($pair in $rawXmlReplacements) {
            $text = $text.Replace($pair[0], $pair[1])
        }
        Save-EntryText -Zip $Zip -Name $entry.FullName -Text $text
    }
}

function Replace-Images {
    param([System.IO.Compression.ZipArchive]$Zip)

    for ($i = 1; $i -le 52; $i++) {
        $name = "word/media/image$i.png"
        $entry = $Zip.GetEntry($name)
        if ($null -eq $entry) { continue }

        $width = 1200
        $height = 760
        $stream = $entry.Open()
        try {
            $img = [System.Drawing.Image]::FromStream($stream)
            try {
                $width = [Math]::Max(700, $img.Width)
                $height = [Math]::Max(460, $img.Height)
            } finally {
                $img.Dispose()
            }
        } catch {
            $width = 1200
            $height = 760
        } finally {
            $stream.Dispose()
        }

        $spec = $imageSpecs[$i]
        if ($null -eq $spec) {
            $spec = @{ Title="DanTalk figure $i"; Mode='diagram'; Lines=@('DanTalk','Android','Firebase','Supabase') }
        }
        $bytes = New-ImageBytes -Width $width -Height $height -Spec $spec
        $entry.Delete()
        $newEntry = $Zip.CreateEntry($name, [System.IO.Compression.CompressionLevel]::Optimal)
        $out = $newEntry.Open()
        try {
            $out.Write($bytes, 0, $bytes.Length)
        } finally {
            $out.Dispose()
        }
    }
}

